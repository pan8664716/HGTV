package com.hgtv.star.core

/**
 * 两条「知情同意」的正文与标题，**两端共用一份**。
 *
 * 这两段文字是产品承诺的一部分：电视端与手机端说的是不是同一件事，不该靠两份拷贝
 * 各自维护。文案改一处、两端同时生效，也就不会出现「电视上说了风险、手机上没说」。
 *
 * 两条是**不同**的弹窗，语义也不一样：
 *
 * * [USAGE]（[USAGE_TITLE]）：告知「这是第三方客户端」，确认一次就记住
 *   （落在 `Library.thirdPartyAccepted`），之后进「我的」页不再打扰；
 * * [SMS]（[SMS_TITLE]）：**每一次**点「获取验证码」都要过一遍。它问的不是
 *   「你知不知道这是第三方应用」，而是「这一次要不要真的把手机号发给平台」——
 *   每次发码都是一次独立的、可撤销的决定，因此不能拿上一次的确认顶替，也不落盘。
 */
object ThirdPartyNotice {

    const val USAGE_TITLE = "使用须知"

    const val SMS_TITLE = "发送验证码前请确认"

    /** 使用须知正文。 */
    val USAGE = """
        本应用是第三方客户端，与内容平台官方无任何关联，也未获得官方授权。

        使用本应用登录账号，属于在非官方客户端上使用服务。若因违反平台规则（包括但不限于多设备登录、异常客户端识别等）导致账号被限制、封禁或其他处置，本应用不承担任何责任，也无法代为申诉或恢复。

        请自行评估风险。继续使用即表示你已知晓并接受上述情况。
    """.trimIndent()

    /** 发码确认正文：比使用须知短，因为这一段只交代「这一下要发生什么、风险在哪」。 */
    val SMS = """
        接下来会把手机号发送到内容平台并请求一条登录验证码。

        这属于在非官方客户端上登录：若因违反平台规则导致账号被限制、封禁或其他处置，本应用不承担任何责任，也无法代为申诉或恢复。

        点击「我已知晓并同意使用」后才会发送验证码；点击「不同意」不会发出任何请求。
    """.trimIndent()

    /** 两枚按钮的文案：两端同一份，避免一端写「同意」另一端写「我知道了」。 */
    const val ACCEPT = "我已知晓并同意使用"
    const val DECLINE = "不同意"
}
