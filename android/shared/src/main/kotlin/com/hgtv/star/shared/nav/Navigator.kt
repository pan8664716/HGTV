package com.hgtv.star.shared.nav

/**
 * 页面跳转的唯一入口。
 *
 * 业务代码只认「去哪一页、带什么参数」，由各端实现决定这句话在自己的容器里怎么落地：
 *
 * | 端 | 实现 | `open()` 实际做的事 |
 * | --- | --- | --- |
 * | 电视 | `TvNavigator` | 切 `screen` + 重建视图树；必要时先按返回键的语义收尾 |
 * | 手机 | `PhoneNavigator` | 组装 `Intent` + `startActivity`，交给系统返回栈 |
 *
 * ## 为什么只有一个方法
 *
 * 刻意**没有** `back()`：电视的返回由 `MainActivity.onBackPressed` 统一处理（它要按
 * `screen` / 浮层 / 焦点三层判断），手机的返回由系统栈处理。两边都不需要导航器代劳，
 * 加一个谁都不实现的空方法只会变成噪音。
 *
 * 也刻意没有 `current`：电视知道当前 `screen`，手机得靠每个 `Activity` 自报，
 * 为一个「拿不全」的只读属性付出注册成本不划算。需要页面名时各端自己给。
 *
 * ## 实现方约定
 *
 * * 必须**穷尽** [Route] 的所有分支。`when` 不写 `else`，这样新增页面时编译失败，
 *   而不是在运行时静默走进某个默认分支；
 * * 不要在这个方法里做业务（取详情、起播放器）：它只负责「把用户送到那一页」，
 *   页面自己要加载什么由页面自己决定。
 */
interface Navigator {

    /**
     * 打开 [route] 对应的页面。
     *
     * @return `false` = **这一端打不开**（没有这个页面，或缺少打开它必需的数据）。
     *   调用方据此走自己的兜底，而不是让用户停在一片空白上。
     *
     *   这条返回值是给电视端准备的：它按 `seriesId` 进详情 / 播放时，要靠本机历史
     *   把 `Series` 反查出来（那个对象带着列表接口才有的 `notice`），查不到就说明
     *   这一部已经不在这台机器上了，此时应当退回首页而不是打开一个空壳详情页。
     *   手机端恒为 `true`——它只传 id，页面自己去取。
     */
    fun open(route: Route): Boolean
}
